interface WarningInput {
  pages: AnalyzedPage[];
  generated: GeneratedRules;
  priority: AttributePriority;
  weakSelectors: { total: number; withheld: number; pages: string[] };
  piiCounts: PiiCounts;
  truncations: TruncationEntry[];
  unconfirmedNoise: UnconfirmedNoiseEntry[];
}

function warning(
  code: WarningCode,
  severity: ReportWarning["severity"],
  message: string,
  pages: string[] = [],
  count = pages.length,
): ReportWarning {
  return { code, severity, message, pages, count };
}

const pagesWhere = (
  pages: AnalyzedPage[],
  test: (page: AnalyzedPage) => boolean,
) => pages.filter(test).map((page) => page.pageId);

export function buildWarnings(input: WarningInput): ReportWarning[] {
  const { pages, generated, piiCounts } = input;
  const warnings: ReportWarning[] = [];
  if (input.weakSelectors.total > 0) {
    warnings.push(
      warning(
        "weak-selectors",
        "warn",
        `${input.weakSelectors.total} selector(s) match more than one element on a page${
          input.weakSelectors.withheld
            ? ` (${input.weakSelectors.withheld} more not shown: their values are not safe to show)`
            : ""
        }. Anchor them with a parent id plus a child class.`,
        input.weakSelectors.pages,
        input.weakSelectors.total,
      ),
    );
  }
  const piiTotal = piiCounts.email + piiCounts.phone + piiCounts.digits;
  if (piiTotal > 0) {
    warnings.push(
      warning(
        "pii-values",
        "warn",
        `${piiTotal} value(s) have a PII shape (emails ${piiCounts.email}, phone numbers ${piiCounts.phone}, runs of 5+ digits ${piiCounts.digits}). None of them is stored in this report.`,
        [],
        piiTotal,
      ),
    );
  }
  warnings.push(
    warning(
      "names-not-detected",
      "info",
      "Person names have no shape and cannot be detected. Review rules, examples and diffs before sharing this report.",
    ),
  );
  const incomplete = pagesWhere(pages, (p) => p.runs.some((r) => r.incomplete));
  if (incomplete.length) {
    warnings.push(
      warning(
        "incomplete-capture",
        "warn",
        "Some runs are incomplete; they feed no observed-change rule.",
        incomplete,
      ),
    );
  }
  const mismatched = pagesWhere(pages, (p) =>
    p.runs.some((r) => r.meta.stateMismatch),
  );
  if (mismatched.length) {
    warnings.push(
      warning(
        "state-mismatch",
        "warn",
        "Some runs did not reach the same state as the first run; they feed no observed-change rule.",
        mismatched,
      ),
    );
  }
  const single = pagesWhere(pages, (p) => p.runs.length < 2);
  if (single.length) {
    warnings.push(
      warning(
        "single-run-pages",
        "warn",
        "Pages with one run: capture a second run to detect changing values.",
        single,
      ),
    );
  }
  if (!hasTestAttributes(input.priority)) {
    warnings.push(
      warning(
        "no-test-attributes",
        "info",
        "No test attributes (data-automation-id, data-testid, data-test) were found. Asking the application team for them would give the most stable selectors.",
      ),
    );
  }
  if (generated.rejectedRules.length) {
    warnings.push(
      warning(
        "rejected-rules",
        "info",
        `${generated.rejectedRules.length} rule(s) were rejected because they would also ignore stable values.`,
        [],
        generated.rejectedRules.length,
      ),
    );
  }
  const inconsistent = pagesWhere(
    pages,
    (p) => new Set(p.runs.map((r) => r.meta.aptyPresent)).size > 1,
  );
  if (inconsistent.length) {
    warnings.push(
      warning(
        "apty-inconsistent",
        "warn",
        "Apty was present in some runs and absent in others. A console-script profile cannot tell which element a value belongs to, so differences between those runs may include Apty's own elements.",
        inconsistent,
      ),
    );
  }
  if (input.truncations.length) {
    warnings.push(
      warning(
        "truncated",
        "warn",
        "Some values or runs were cut to the size limits; see Truncations.",
        sortedUnique(input.truncations.map((t) => t.pageId)),
        input.truncations.length,
      ),
    );
  }
  if (input.unconfirmedNoise.length) {
    warnings.push(
      warning(
        "unconfirmed-noise",
        "info",
        "Possible noise that is not confirmed was found and not applied; see Unconfirmed noise.",
        [],
        input.unconfirmedNoise.length,
      ),
    );
  }
  if (generated.coveredByDefaults.length) {
    warnings.push(
      warning(
        "covered-by-defaults",
        "info",
        DEFAULTS_ASSUMPTION,
        [],
        generated.coveredByDefaults.length,
      ),
    );
  }
  const closed = pagesWhere(pages, (p) =>
    p.runs.some((r) =>
      r.shadowHosts.some((h) => !h.noise && h.mode !== "open"),
    ),
  );
  if (closed.length) {
    warnings.push(
      warning(
        "closed-shadow-roots",
        "warn",
        "Closed shadow roots: the extension read them, but a page script cannot. Whether Apty's Shadow DOM support reaches closed roots is not known; check these components in Apty.",
        closed,
      ),
    );
  }
  const legacy = pagesWhere(pages, (p) =>
    p.runs.some((r) => !r.seesClosedShadowRoots),
  );
  if (legacy.length) {
    warnings.push(
      warning(
        "legacy-closed-shadow-roots",
        "info",
        "Console-script profiles cannot see closed shadow roots.",
        legacy,
      ),
    );
  }
  const large = largeDomPages(pages);
  if (large.length) {
    warnings.push(
      warning(
        "large-dom",
        "info",
        "Large DOM: more than 2,000 div elements.",
        large,
      ),
    );
  }
  if (generated.rulesDropped > 0) {
    warnings.push(
      warning(
        "rule-cap",
        "warn",
        `${generated.rulesDropped} rule(s) beyond the limit were left out.`,
        [],
        generated.rulesDropped,
      ),
    );
  }
  return warnings;
}

export function buildNotMeasured(
  report: Pick<
    DomConfigReport,
    "debounce" | "ignoreEvents" | "maxZIndex" | "shadowDom" | "unconfirmedNoise"
  >,
): NotMeasuredEntry[] {
  const entries: NotMeasuredEntry[] = [];
  if (report.debounce.basis === "default") {
    entries.push({ item: "DOM change debounce", text: report.debounce.reason });
  } else {
    entries.push({
      item: "DOM change debounce",
      text: "Derived by a heuristic, not measured directly.",
    });
  }
  if (report.ignoreEvents.basis === "default") {
    entries.push({
      item: "Ignore DOM events",
      text: report.ignoreEvents.reason,
    });
  }
  if (report.maxZIndex.basis === "default") {
    entries.push({ item: "Max z-index", text: report.maxZIndex.reason });
  }
  if (report.shadowDom.basis === "default") {
    entries.push({
      item: "Enable Shadow DOM support",
      text: report.shadowDom.reason,
    });
  }
  entries.push(
    { item: "Container score threshold", text: "Default, not measured." },
    { item: "Click-advance", text: "Default, not measured." },
    {
      item: "Rule semantics",
      text: "How Apty reads id and class rules, the Regex flavor and In lists are assumptions (D7).",
    },
  );
  if (report.unconfirmedNoise.length) {
    entries.push({
      item: "Unconfirmed noise",
      text: `${report.unconfirmedNoise.map((e) => e.marker).join(", ")}: listed, not applied.`,
    });
  }
  return entries;
}
