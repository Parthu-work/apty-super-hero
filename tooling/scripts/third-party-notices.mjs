#!/usr/bin/env node
/**
 * Writes apps/browser-extension/THIRD_PARTY_NOTICES.txt from
 * `pnpm licenses list --prod --json`: every production package, its licence
 * and the licence text it ships. With --check, fails if the committed file is
 * out of date instead of writing it.
 *
 * Usage: node tooling/scripts/third-party-notices.mjs [--check]
 */
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../..", import.meta.url));
export const NOTICES_PATH = join(
  root,
  "apps/browser-extension/THIRD_PARTY_NOTICES.txt",
);

const LICENCE_FILE = /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i;

/** The licence text a package ships, or null. */
export function readLicenceText(packageDir) {
  if (!existsSync(packageDir)) return null;
  const file = readdirSync(packageDir).find((name) => LICENCE_FILE.test(name));
  return file
    ? readFileSync(join(packageDir, file), "utf8").replace(/\r\n/g, "\n").trim()
    : null;
}

/**
 * `pnpm licenses list --json` groups packages by licence and lists each
 * version's install path; this flattens it into one entry per name@version.
 */
export function packagesFromPnpm(report) {
  const entries = [];
  for (const [licence, packages] of Object.entries(report)) {
    for (const pkg of packages) {
      pkg.versions.forEach((version, i) => {
        entries.push({
          name: pkg.name,
          version,
          licence,
          homepage: pkg.homepage ?? "",
          dir: pkg.paths[i] ?? pkg.paths[0],
        });
      });
    }
  }
  return entries.sort(
    (a, b) =>
      a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
  );
}

export function renderNotices(entries, readText = readLicenceText) {
  const sections = entries.map((entry) => {
    const text = readText(entry.dir);
    const body =
      text ??
      `The package ships no licence file. Licence: ${entry.licence}${
        entry.homepage ? `; see ${entry.homepage}` : ""
      }.`;
    return `${entry.name}@${entry.version} (${entry.licence})\n\n${body}`;
  });
  return `${[
    "THIRD-PARTY SOFTWARE NOTICES",
    "",
    "Apty Agent includes the following third-party packages. Generated by",
    "tooling/scripts/third-party-notices.mjs from pnpm licenses list --prod;",
    "do not edit by hand. The Inter font's licence is in",
    "assets/Inter-OFL.txt.",
    "",
    `${entries.length} packages.`,
    "",
    ...sections.flatMap((section) => ["=".repeat(72), "", section, ""]),
  ].join("\n")}`;
}

function main() {
  const json = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  const notices = renderNotices(packagesFromPnpm(JSON.parse(json)));
  if (process.argv.includes("--check")) {
    const current = existsSync(NOTICES_PATH)
      ? readFileSync(NOTICES_PATH, "utf8")
      : "";
    if (current !== notices) {
      console.error(
        "✗ THIRD_PARTY_NOTICES.txt is out of date; run node tooling/scripts/third-party-notices.mjs",
      );
      process.exit(1);
    }
    console.log(
      "✓ THIRD_PARTY_NOTICES.txt matches the production dependencies",
    );
    return;
  }
  writeFileSync(NOTICES_PATH, notices);
  console.log(`✓ wrote ${NOTICES_PATH}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
