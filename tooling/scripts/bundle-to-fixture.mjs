#!/usr/bin/env node
/**
 * Turns a DOM Health validation bundle (Export validation bundle in the DOM
 * Health card) into the start of a regression fixture, for runbook section
 * 9 ("Lock it in"):
 *
 *   <name>.html            a frame-tree skeleton: every frame the bundle saw,
 *                          keyed the way the audit keyed it, and a
 *                          placeholder for every overlay it left out
 *   <name>.values.json     the measured values to copy into values.ts
 *   <name>.fixture.test.ts a test stub, one `it.todo` per check to write
 *
 * The bundle carries no page text; hosts are replaced with
 * `*.example.test` here as well, the way the existing ERP fixtures are
 * redacted. The skeleton is not the application: fill in the structure
 * from a redacted DOM export before relying on it.
 *
 * Usage: node tooling/scripts/bundle-to-fixture.mjs <bundle.json> <name> [--out <dir>]
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SUPPORTED_SCHEMA = "apty-dom-health-validation/1";
const DEFAULT_OUT = "packages/dom-snapshot/src/__tests__/fixtures/erp";
const NAME_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

function escapeAttr(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;");
}

/** Every host in the bundle → `host-N.example.test`, in order of first appearance. */
export function hostMap(bundle) {
  return new Map(
    (bundle.hosts ?? []).map((host, i) => [host, `host-${i + 1}.example.test`]),
  );
}

function redactHosts(text, hosts) {
  let out = text;
  for (const [real, fake] of hosts) out = out.replaceAll(real, fake);
  return out;
}

function auditOf(bundle) {
  return bundle.page ?? bundle.application?.pages?.[0]?.audit ?? null;
}

function frameAttributes(frame, hosts) {
  const attrs = [];
  if (frame.keySource === "osp-id")
    attrs.push(`data-osp-id="${escapeAttr(frame.key)}"`);
  if (frame.keySource === "id") attrs.push(`id="${escapeAttr(frame.key)}"`);
  if (frame.keySource === "name") attrs.push(`name="${escapeAttr(frame.key)}"`);
  if (frame.keySource === "title") attrs.push('title="TODO: redacted title"');
  if (frame.urlTemplate) {
    attrs.push(`src="${escapeAttr(redactHosts(frame.urlTemplate, hosts))}"`);
  }
  return attrs.join(" ");
}

/** Placeholder markup for an overlay matcher (`id:prefix`, `class:prefix`, `tag:name`). */
export function overlayPlaceholder(matcher) {
  const [kind, value = ""] = String(matcher).split(":");
  const safe = escapeAttr(value);
  if (kind === "id") return `<div id="${safe}placeholder"></div>`;
  if (kind === "class") return `<div class="${safe}placeholder"></div>`;
  if (kind === "tag" && /^[a-z][a-z0-9-]*$/.test(value))
    return `<${value}></${value}>`;
  return `<!-- overlay ${escapeAttr(matcher)}: no placeholder for this matcher -->`;
}

export function fixtureHtml(bundle, name) {
  const hosts = hostMap(bundle);
  const audit = auditOf(bundle);
  const frames = audit?.frames ?? [];
  const lines = [
    "<!doctype html>",
    `<!-- Skeleton for ${name}, generated by tooling/scripts/bundle-to-fixture.mjs from a ${bundle.schema} bundle (${bundle.generatedAt}). It holds the frame tree and overlays only: replace it with a redacted DOM export's structure, and record provenance in README.md. -->`,
    "<html>",
    "<head><title>TODO: redacted title</title></head>",
    "<body>",
  ];
  const byParent = new Map();
  for (const frame of frames) {
    const list = byParent.get(frame.parentFrameId) ?? [];
    list.push(frame);
    byParent.set(frame.parentFrameId, list);
  }
  const top = frames.find((f) => f.parentFrameId === -1);
  for (const child of byParent.get(top?.frameId ?? 0) ?? []) {
    lines.push(
      `<!-- frame ${child.frameId}: role ${child.role} (${child.roleReason}); status ${child.status}${child.error ? `: ${child.error}` : ""}; key from ${child.keySource}${child.keyStable ? "" : ", unstable"} -->`,
    );
    lines.push(`<iframe ${frameAttributes(child, hosts)}></iframe>`);
    const nested = byParent.get(child.frameId) ?? [];
    if (nested.length > 0) {
      lines.push(
        `<!-- frame ${child.frameId} holds ${nested.length} frame(s) of its own: ${nested.map((f) => `${f.keySource}:${f.key ?? f.keyHash} (${f.role})`).join(", ")}; add them to a separate document if they matter -->`,
      );
    }
  }
  for (const overlay of audit?.overlays ?? []) {
    lines.push(
      `<!-- overlay ${overlay.owner ?? "unknown"} (${overlay.evidence}): ${overlay.roots} root(s), ${overlay.elementCount} element(s) -->`,
    );
    lines.push(overlayPlaceholder(overlay.matcher));
  }
  lines.push(
    "<main><!-- TODO: the application's structure, redacted --></main>",
  );
  lines.push("</body>", "</html>", "");
  return lines.join("\n");
}

export function fixtureValues(bundle) {
  const hosts = hostMap(bundle);
  const audit = auditOf(bundle);
  return JSON.parse(
    redactHosts(
      JSON.stringify({
        schema: bundle.schema,
        generatedAt: bundle.generatedAt,
        versions: bundle.versions,
        frames: (audit?.frames ?? []).map((f) => ({
          key: f.key,
          keySource: f.keySource,
          role: f.role,
          status: f.status,
          urlTemplate: f.urlTemplate,
        })),
        overlays: (audit?.overlays ?? []).map((o) => ({
          matcher: o.matcher,
          evidence: o.evidence,
          elementCount: o.elementCount,
        })),
        coverage: audit?.coverage ?? null,
        duplicateIds: audit?.duplicateIds ?? null,
        virtualized: audit?.virtualized ?? null,
        performance: audit?.performance ?? null,
        application: bundle.application
          ? {
              coverage: bundle.application.coverage,
              states: bundle.application.states,
              traversal: bundle.application.traversal,
            }
          : null,
        routeProbe: bundle.routeProbe?.analysis ?? null,
        thresholdOverrides: bundle.thresholdOverrides,
      }),
      hosts,
    ),
  );
}

export function fixtureTestStub(bundle, name) {
  const audit = auditOf(bundle);
  const todos = [];
  for (const frame of audit?.frames ?? []) {
    if (frame.parentFrameId === -1) continue;
    const label = frame.key ?? `frame ${frame.frameId}`;
    todos.push(`classifies ${label} as ${frame.role}`);
    if (frame.status === "failed") {
      todos.push(`reports why ${label} could not be read`);
    }
  }
  for (const overlay of audit?.overlays ?? []) {
    todos.push(`leaves out ${overlay.matcher} as an overlay`);
  }
  if ((audit?.virtualized?.containers ?? 0) > 0) {
    todos.push(
      `detects ${audit.virtualized.containers} virtualized list(s) (${audit.virtualized.observedItems} of ${audit.virtualized.declaredTotal ?? "?"} rows rendered)`,
    );
  }
  if (bundle.application?.traversal) {
    todos.push(`chooses ${bundle.application.traversal.mode} traversal`);
  }
  if (todos.length === 0)
    todos.push("covers the behaviour this fixture was added for");
  return [
    `import { describe, it } from "vitest";`,
    `import { readErpFixture } from "./fixtures/erp/load-fixture";`,
    "",
    `// Generated by tooling/scripts/bundle-to-fixture.mjs. Add "${name}" to ErpFixtureName,`,
    `// then turn each todo into a test that fails without the change it locks in.`,
    `describe("${name} fixture", () => {`,
    `  it("loads", () => {`,
    `    readErpFixture("${name}" as Parameters<typeof readErpFixture>[0]);`,
    "  });",
    ...todos.map((todo) => `  it.todo(${JSON.stringify(todo)});`),
    "});",
    "",
  ].join("\n");
}

export function bundleToFixture(bundle, name) {
  if (bundle?.schema !== SUPPORTED_SCHEMA) {
    throw new Error(
      `Expected a ${SUPPORTED_SCHEMA} bundle, got ${JSON.stringify(bundle?.schema)}`,
    );
  }
  if (!NAME_PATTERN.test(name)) {
    throw new Error(`Fixture name must be kebab-case, got "${name}"`);
  }
  return {
    [`${name}.html`]: fixtureHtml(bundle, name),
    [`${name}.values.json`]: `${JSON.stringify(fixtureValues(bundle), null, 2)}\n`,
    [`../../${name}.fixture.test.ts`]: fixtureTestStub(bundle, name),
  };
}

function main(argv) {
  const args = [...argv];
  const outIndex = args.indexOf("--out");
  const outDir = resolve(
    outIndex >= 0 ? args.splice(outIndex, 2)[1] : DEFAULT_OUT,
  );
  const [bundlePath, name] = args;
  if (!bundlePath || !name) {
    console.error(
      "Usage: node tooling/scripts/bundle-to-fixture.mjs <bundle.json> <name> [--out <dir>]",
    );
    return 2;
  }
  const files = bundleToFixture(
    JSON.parse(readFileSync(bundlePath, "utf8")),
    name,
  );
  const targets = Object.keys(files).map((file) => join(outDir, file));
  const existing = targets.filter((target) => existsSync(target));
  if (existing.length > 0) {
    console.error(`Refusing to overwrite: ${existing.join(", ")}`);
    return 1;
  }
  mkdirSync(outDir, { recursive: true });
  for (const [file, content] of Object.entries(files)) {
    writeFileSync(join(outDir, file), content);
    console.log(`wrote ${join(outDir, file)}`);
  }
  return 0;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  process.exitCode = main(process.argv.slice(2));
}
